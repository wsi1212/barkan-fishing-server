def main():
    J = json.load(open(SRC, encoding="utf-8"))
    Q = J["퀘스트"]
    before_daily = {k: list(v) for k, v in J["일일"].items()}
    before_weekly = list(J["주간"])

    # ── 1. 일일 신설 ──
    added_d = 0
    for diff, items in DAILY_NEW.items():
        lv = J["난이도레벨"][diff]
        for qid, name, goal, desc, money, xp, hard in items:
            Q[qid] = {"id": qid, "이름": name, "설명": desc, "목표": [goal],
                      "타입": "농사" if "농사" in qid else "광질" if "광질" in qid else "채집",
                      "카테고리": "일일", "필요레벨": lv,
                      "보상돈": money, "보상경험치": xp, "난이도": hard}
            added_d += 1

    # ── 2. 주간 신설 ──
    added_w = 0
    for qid, name, goal, band, desc, money, typ, hard in WEEKLY_NEW:
        lo, hi = band
        q = {"id": qid, "이름": name, "설명": desc, "목표": [goal],
             "타입": typ, "카테고리": "주간", "필요레벨": lo,
             "보상돈": money, "보상경험치": 0, "난이도": hard}
        if hi:
            q["최대레벨"] = hi
        Q[qid] = q
        added_w += 1

    # ── 3. 접는 퀘스트 (정의까지 삭제 — prune 이 플레이어 데이터를 자동 치유) ──
    dropped = []
    for qid in DAILY_DROP + WEEKLY_DROP:
        if Q.pop(qid, None) is not None:
            dropped.append(qid)

    # ── 4. 풀 재작성 ──
    J["일일"] = {d: list(order) for d, order in DAILY_ORDER.items()}
    weekly = [k for k in J["주간"] if k in Q]
    weekly += [q[0] for q in WEEKLY_NEW]
    J["주간"] = weekly

    # ── 5. 검산 ──
    errs = []
    for diff, pool in J["일일"].items():
        for qid in pool:
            if qid not in Q:
                errs.append(f"일일[{diff}] 정의 없음: {qid}")
        if len(pool) != len(set(pool)):
            errs.append(f"일일[{diff}] 중복")
    for qid in J["주간"]:
        if qid not in Q:
            errs.append(f"주간 정의 없음: {qid}")
    # 삭제한 퀘스트를 아무도 선행/다음으로 가리키면 안 된다
    gone = set(dropped)
    for k, v in Q.items():
        for f in ("선행퀘스트", "다음퀘스트"):
            for ref in str(v.get(f, "")).replace(",", " ").split():
                if ref in gone:
                    errs.append(f"{k}.{f} → 삭제된 {ref}")
    # 주간 계열별 구간 겹침·구멍 검사
    for qid in J["주간"]:
        v = Q[qid]
        lo, hi = v.get("필요레벨", 1), v.get("최대레벨", 0)
        if hi and lo > hi:
            errs.append(f"{qid} 구간 역전 {lo}~{hi}")
    if errs:
        print("\n".join("🔴 " + e for e in errs))
        sys.exit(1)

    json.dump(J, open(SRC, "w", encoding="utf-8"), ensure_ascii=False, indent=2)

    # ── 6. 리포트 ──
    print(f"일일 신설 {added_d} · 주간 신설 {added_w} · 접음 {len(dropped)}")
    print("접음:", " ".join(dropped))
    print()
    print("=== 일일 풀 ===")
    for diff, pool in J["일일"].items():
        n_old = len(before_daily.get(diff, []))
        print(f"[{diff}] Lv{J['난이도레벨'][diff]}  {n_old}칸 → {len(pool)}칸")
        for qid in pool:
            v = Q[qid]
            print(f"   {v['목표'][0]:24} 돈{v.get('보상돈',0):>7} xp{v.get('보상경험치',0):>5}  {qid}")
    print()
    print("=== 주간 활성 개수 (레벨별) ===")
    for lv in (5, 12, 25, 50):
        act = [q for q in J["주간"]
               if Q[q].get("필요레벨", 1) <= lv
               and (Q[q].get("최대레벨", 0) == 0 or lv <= Q[q]["최대레벨"])]
        by = collections.Counter(Q[q].get("타입", "?") for q in act)
        print(f"  Lv{lv:>2}: {len(act):>2}칸  " + " ".join(f"{k}{v}" for k, v in sorted(by.items())))
    print()
    print("=== 주간 비낚시 계열 ===")
    for lv in (5, 12, 25, 50):
        row = []
        for q in J["주간"]:
            v = Q[q]
            if v.get("타입") not in ("농사", "광질", "채집"):
                continue
            if v.get("필요레벨", 1) > lv:
                continue
            if v.get("최대레벨", 0) and lv > v["최대레벨"]:
                continue
            row.append(v["목표"][0])
        print(f"  Lv{lv:>2}: " + "  ".join(row))
    print(f"\n주간 {len(before_weekly)} → {len(J['주간'])}")


if __name__ == "__main__":
    main()
