def dish_unlock():
    """요리 표시명 → 해금 레벨. ★DishSpecs.unlockTier 의 분기를 그대로 옮긴다.

    ★d.tier 를 그냥 읽으면 틀린다 — 2026-08-28 실제로 그렇게 틀렸다. 「따뜻한 빵」은
    d.tier=2 지만 FREE_DISHES 라 unlockTier=0(무해금)이다. 튜토리얼(튜토_요리1/2)이
    필수로 쓰기 때문에 일부러 초반으로 뺀 요리인데, tier 만 보고 Lv10 으로 오독했다.
    """
    src = open(_DISH, encoding="utf-8").read()
    lv = {0: 0, 1: 1, 2: 10, 3: 23, 4: 35}
    m = re.search(r"UNLOCK_LEVEL = \{([^}]*)\}", src)
    if m:
        lv = {i: int(x) for i, x in enumerate(re.findall(r"\d+", m.group(1)))}
    free = set(re.findall(r'"([^"]+)"',
               re.search(r"FREE_DISHES = [^(]*\(([^)]*)\)", src, re.S).group(1)))
    ov = dict(re.findall(r'"([^"]+)",\s*(\d)',
              re.search(r"UNLOCK_TIER_OVERRIDE = [^(]*\((.*?)\);", src, re.S).group(1)))
    out = {}
    for m in re.finditer(r'(buff|submit|heal)\(\s*"([^"]+)"\s*,\s*"([^"]+)"\s*,'
                         r'\s*Material\.\w+\s*,\s*(\d+)', src):
        kind, did, name, tier = m.group(1), m.group(2), m.group(3), int(m.group(4))
        t = 0 if (kind == "heal" or did in free) else int(ov.get(did, max(1, min(4, tier))))
        out[re.sub(r"§.", "", name).strip()] = lv.get(t, 0)
    if not out:
        raise SystemExit("★DishSpecs 를 못 읽었다 — 요리 해금레벨 파생 중단")
    return out


DISH_UNLOCK = dish_unlock()

