#: 신규 재료 소비처 — S급 레시피에 넣는다. 소비처가 없으면 다시 고아가 된다.
#  A급 배선은 사막·상단·왕도 감사 때 같이 본다(그 마을들은 아직 미감사).
NEW_SINKS = {
    "바르칸 낚싯대": [("용비늘", 3), ("용암수지", 4)],
    "천공의 낚싯대": [("용비늘", 3), ("고대비늘", 4)],
    "천공의 작살": [("고대비늘", 4)],
    "바르칸 작살": [("용암수지", 3)],
    "심해 잠수 작살": [("심해수정", 4)],
    "심연의 작살": [("심해수정", 4)],
    "압력관통 작살": [("심해수정", 3)],
}
MC_ITEM = {"용비늘": "phantom_membrane", "심해수정": "prismarine_shard",
           "고대비늘": "turtle_scute", "용암수지": "magma_cream"}


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    src, apply_ = sys.argv[1], "--apply" in sys.argv
    mp, rp = os.path.join(src, "materials.json"), os.path.join(src, "recipes.json")
    M = json.load(open(mp, encoding="utf-8"))
    R = json.load(open(rp, encoding="utf-8"))
    dt, mats = M["dropTables"], M["materials"]

    # ── 1. 낚시가 성립하지 않는 지역 제거 ──────────────────────────────
    print("[드랍표 삭제]")
    for area, why in DROP_REGIONS.items():
        if area in dt:
            n = len(dt[area])
            tot = sum(e["chance"] for e in dt[area])
            del dt[area]
            print(f"  · {area:<12}{n}종 {tot}% 제거 — {why}")
        else:
            print(f"  = {area} 이미 없음")

    # ── 2. 신규 재료 정의 확인 (고아 되살리기) ────────────────────────
    print("\n[신규 고급 재료] — 전부 기존 정의(고아)를 되살린다")
    for m, area in NEW_MATS.items():
        if m not in mats:
            sys.exit(f"❌ {m} 정의가 materials.json 에 없다 — 새로 만들어야 한다")
        print(f"  · {m:<8}→ {area:<14}«{mats[m]['desc']}»")

    # ── 3. 드랍표 재설계 ───────────────────────────────────────────────
    old = {a: {e["matId"]: e["chance"] for e in t} for a, t in dt.items()}
    for area, rows in TABLES.items():
        dt[area] = [{"matId": m, "chance": c} for m, c in rows]
    extra = [a for a in dt if a not in TABLES]
    if extra:
        sys.exit(f"❌ 설계표에 없는 지역이 남았다: {extra}")

    print(f"\n[드랍표 재설계] {len(TABLES)}지역")
    print(f"  {'지역':<16}{'전':>10}{'후':>10}   변화")
    for area, rows in TABLES.items():
        o = old.get(area, {})
        n = {m: c for m, c in rows}
        ot, nt = sum(o.values()), sum(n.values())
        add = [m for m in n if m not in o]
        rem = [m for m in o if m not in n]
        chg = [f"{m} {o[m]}→{n[m]}" for m in n if m in o and o[m] != n[m]]
        parts = []
        if add:
            parts.append("+" + ",".join(add))
        if rem:
            parts.append("−" + ",".join(rem))
        if chg:
            parts.append(" · ".join(chg))
        print(f"  {area:<16}{f'{len(o)}종 {ot}%':>10}{f'{len(n)}종 {nt}%':>10}   "
              + ("; ".join(parts) if parts else "변화 없음"))

    # ── 4. 신규 재료 소비처 ────────────────────────────────────────────
    idx = {}
    for rid, r in R["recipes"].items():
        for k in ("resultPartName", "rodPartName"):
            if r.get(k):
                idx[r[k]] = r
    print("\n[신규 재료 소비처] S급 레시피")
    for item, adds in NEW_SINKS.items():
        r = idx.get(item)
        if not r:
            sys.exit(f"❌ {item} 레시피를 찾지 못했다")
        for mid, qty in adds:
            if any(i["typeOrMatId"] == mid for i in r["ingredients"]):
                print(f"  = {item}: {mid} 이미 있음")
                continue
            r["ingredients"].append({"kind": "custom", "typeOrMatId": mid,
                                     "displayName": mats[mid]["name"],
                                     "mcItem": MC_ITEM[mid], "qty": qty})
            print(f"  · {item:<14}+ {mats[mid]['name']}×{qty}")

    # ── 5. 검증 ────────────────────────────────────────────────────────
    allm = sorted({e["matId"] for t in dt.values() for e in t})
    excl = {}
    for m in allm:
        s = [a for a, t in dt.items() if any(e["matId"] == m for e in t)]
        if len(s) == 1:
            excl.setdefault(s[0], []).append(m)
    print(f"\n[검증] 지역 {len(dt)} · 재료 {len(allm)}종")
    print(f"  전용 재료 있는 지역 {len(excl)}/{len(dt)}"
          "   (상단마을은 의도적 예외 — 마을은 낚시 스팟이 아니다)")
    for a in dt:
        tot = sum(e["chance"] for e in dt[a])
        print(f"    {a:<16}{tot:>4}%  {', '.join(excl.get(a, [])) or '— (마을: 전용 없음)'}")
    for m in ("진주", "별빛진주"):
        ch = sorted({e["chance"] for t in dt.values() for e in t if e["matId"] == m})
        print(f"  {m} 확률 분포 {ch}" + ("  🔴 여전히 균일" if len(ch) == 1 else "  🟢 기울기 있음"))
    sinkless = [m for m in NEW_MATS
                if not any(any(i["typeOrMatId"] == m for i in r["ingredients"])
                           for r in R["recipes"].values())]
    print(f"  신규 재료 소비처 없음: {sinkless or '없음 🟢'}")

    if not apply_:
        print("\n[dry-run] --apply 로 실제 반영")
        return
    for path, data in ((mp, M), (rp, R)):
        shutil.copy(path, path + ".bak-matdist")
        json.dump(data, open(path, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print("\n✅ materials.json · recipes.json 반영 (백업 *.bak-matdist)")
    print("   ★LP 그림자가격이 바뀐다 — 전 아이템 재료비 재산출. /데이터리로드 또는 재시작.")


if __name__ == "__main__":
    main()
