#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""재료 지역 분배 재설계 (2026-08-27).

유저 지시:
  · "각 지역마다 가기 어려울수록 더 희귀하고 좋은게 나오고 개수, 확률이 늘어나는가.
     그렇다고 정상같은데 모든게 다 나오는건 아니고 강 전용 늪지대 전용 이런게 있는가"
  · "재료는 너가 중요한걸 하나 놓쳤는데 물고기 판매와 떨어진 거리가 정말 중요함.
     난이도는 강이 더 쉽지만 스폰도시에서 강 가는게 귀찮아서 잘 안가게됨.
     고로 강이 항구보다 더 잘나와야하는게 맞음"   ← **기준점은 항구**(물고기 판매처)
  · "드랍표에만 있는건 드랍표가 잘못된거야 삭제해줘 거기서"
  · 고난이도 지역 보상 = **신규 고급 재료**

────────────────────────────────────────────────────────────────────────────
진단 (material_distribution.py)
────────────────────────────────────────────────────────────────────────────
① 난이도·거리와 드랍이 **역상관**이었다
     난이도 ↔ 합확률 −0.31 · 난이도 ↔ 재료종수 −0.22
     재료티어 ↔ 가장 쉬운 출처 난이도 −0.37   (좋은 재료가 쉬운 곳에 있다)
   가장 쉬운 강이 최고 59% · Lv50 게이트인 원양이 19% · 최원거리 폭포뒤동굴이 18%.
② **전용 재료가 오아시스(7종)에만** 있고 나머지 15지역은 0종.
   그리고 사용처 1·2위인 **진주(204곳)·별빛진주(80곳)가 16/16 지역에서 8%/2% 균일** —
   재료 획득의 절반이 지역과 무관했다.
③ **페리는 미구성**(`ferries.json` 에 `test` 노선 하나) — 이동은 전부 도보/말이라
   **거리가 곧 접근 비용**이다. 유저 지적이 정확했다.

────────────────────────────────────────────────────────────────────────────
접근 비용 = 항구 거리 + 어종 난이도
────────────────────────────────────────────────────────────────────────────
항구(물고기 판매처)에서의 실좌표 거리(폴리곤 면적가중 무게중심)와 어종 풀 평균 등급을
각각 0~1 로 정규화해 더한다. 결과 순서(비용 낮음 → 높음):

    항구 0.04 · 기억의연못 0.38 · 강 0.40 · 오아시스 0.72 · 상단마을 0.79 ·
    레드_로드 0.89 · 대양 1.06 · 붉은사막 1.15 · 협곡 1.21 · 정상 1.47 ·
    폭포_뒤_동굴_1층 1.67 · 늪지대 1.80 · 원양(Lv50 게이트) 최상위

★원양은 폴리곤이 [-5000,-5000]~[5000,5000] 로 **전 맵을 덮는다**. 거리가 무의미하고
  다른 모든 지역과 겹치므로 «Lv50 게이트 최상위»로 따로 둔다. 겹침 자체는 별건.

────────────────────────────────────────────────────────────────────────────
드랍표 삭제 3지역 — 낚시가 성립하지 않는 곳
────────────────────────────────────────────────────────────────────────────
  · **물보라동굴** — regions.json 에 `shape=None · pos1=pos2=[0,0,0] · polygon 0점`.
    **영역이 존재하지 않는다.** 그런데 안개수정 10%(전 지역 최고 출처)가 여기였다.
  · **바르칸 · 스폰도시** — `fish.json.regions` 에 어종 풀이 없다. 어종 풀은 부모 지역
    체인으로 상속되는데(`FishingListener`: 항구 → 스폰도시 → 바르칸) 이 둘은 **상위
    컨테이너**라 자기 어종이 0 이고 부모도 0 이다. 낚을 물고기가 없으면 재료도 안 나온다.

★규칙: **드랍표 항목은 «영역이 있고 어종 풀이 있는» 지역에만 둔다.**
────────────────────────────────────────────────────────────────────────────
사용:
    python3 patch_material_distribution.py <BlockShip 데이터 폴더> [--apply]
"""
import json, os, shutil, sys

