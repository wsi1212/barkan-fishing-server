#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""3챕터 중간보스 「재의 그릇」 복선 심기 (2026-08-14) — **텍스트만. 보스 배선은 아직 아니다.**

■ 왜 지금 이것만 하나
  보스(`붉은사막04`)는 미구현이다. 지금 체인에 끼워 넣으면 라이브 유저가 **Lv26에서 멈춘다**
  — `심해33`이 `심해전왕의핵` 드롭 없이 하드블록인 것과 같은 사고다. 7챕터는 아직 아무도
  도달하지 못했지만 **3챕터는 사람이 지나가는 구간**이라 훨씬 위험하다.
  ⇒ 이 스크립트는 **복선 텍스트만** 심는다. 보스가 돌아가면 그때 체인을 배선한다.

■ 「재의 그릇」이 무엇인가
  교단이 **이프리트를 담으려고 만든 그릇**이다. 그리고 실패했다 —
  짐승의 몸으로는 신을 못 담아서, 담다 만 채 타 버렸다. 속이 빈 껍데기가 제단에서
  흘러내려 **레드로드 호수** 바닥에 가라앉았고, 아직 식지 않았다.

  ★이프리트 본인이 아니다. 그는 죽어서 이 사막이 됐고, 어부는 그를 **죽이는 게 아니라
    기억(조각)을 건진다**(`사막13`·`14`). 심연어가 3챕터에서 일어서면 7챕터 레비아 강림의
    반전도 죽는다.

■ 「그릇」 3연타의 첫 번째
  3챕터 재의 그릇 — **짐승**을 그릇으로 → 실패, 빈 껍데기
  7챕터 사육 수조 — **기른 사역어**를 그릇으로 → 시험 중 (`심해29`가 이미 그렇게 말한다)
  7챕터 볼프람   — **사람**을 그릇으로 → 성공. 그래서 레비아가 나온다
  ⇒ 교단은 처음부터 그릇을 찾고 있었다. 볼프람이 스스로 그릇이 되는 마지막 수가 무거워진다.

■ 왜 여러 번 잡히나 (반복 컨텐츠의 서사적 근거)
  **죽일 게 없다.** 빈 그릇이라 죽는 부분이 없다. 부수면 재가 흩어지고 호수가 식으면 다시
  굳는다. 억지 리스폰이 아니라 **못 죽이는 것이 정체성**이다.
  ↔ 레비아는 **사람**을 담았기 때문에 죽는다. 그릇이 사람이라서.

■ 이 스크립트가 하는 일 (전부 안전, 즉시 배포 가능)
  ① `사막11` 불의 제단 — *"누군가 다녀간 자국"* 을 **눕히려던 빈 자리**로 구체화
  ② `붉은사막01` — **레드로드 호수**를 시야에 넣는다. 아직 가지는 않는다
  ③ `붉은사막02` 수량 불일치 수리 — 목표 `dogam|붉은사막|16`인데 설명은 "12종"이었다
  ④ 카림(`사막11`) 대사 — 자동생성 템플릿 대신 그의 목소리로(과묵한 하오체)

■ 보스 구현 후에 할 일 (여기서는 안 한다)
  `붉은사막04` 「호수에 잠긴 것」 신설 · Lv26 · 수여 유세프 · `material|식지않은재|1`
  체인: `사막12b` → **`붉은사막04`** → `사막13`
  칭호 `화염정복자`를 `붉은사막03`(자하린 낚기)에서 **보스로 이관**
  `사막13` 설명에 "그놈이 깊은 물을 차지하고 있어 실러캔스가 안 올라온다" 추가
  아레나: 레드로드 호수, 반경 14 물 공간(`ImugiBattle` 틀), **낚싯대로 딜**(작살은 7챕터)

사용법 — quests.json·dialogue.json이 있는 디렉터리에서:
    python3 seed_ash_vessel.py
"""
import json, os, re, shutil, sys

QP, DP = "quests.json", "dialogue.json"
Q = json.load(open(QP, encoding="utf-8"))
QUESTS = Q["퀘스트"]
DLG = json.load(open(DP, encoding="utf-8")) if os.path.exists(DP) else None
log = []


def setq(qid, **kw):
    e = QUESTS.get(qid)
    if e is None:
        sys.exit(f"✗ {qid} 없음")
    log.append((qid, e.get("설명"), kw.get("설명")))
    e.update(kw)


# ══ ① 불의 제단 — 그릇을 만들려던 자리 ═══════════════════════════════════════
setq("사막11", 설명=[
    "&7불의 제단에 바칠 공물은 상하면 안 됩니다.",
    "&7&f신선도 85 이상, A등급&7으로 &f2마리&7 준비하세요.",
    "&8제단 한가운데가 움푹 패어 있습니다 — 무언가를 &f눕히려던 자리&7입니다.",
    "&8그리고 그 자리는 비어 있습니다. 눕혔던 것이 일어나 나갔거나, 흘러내렸거나.",
    "&8의뢰: &7카림",
])

# ══ ② 레드로드 호수를 시야에 넣는다 (아직 가지 않는다) ═══════════════════════
setq("붉은사막01", 설명=[
    "&7제단 너머는 마을도 길도 없는",
    "&7이프리트의 등뼈 심층 — &f붉은사막&7입니다.",
    "&7붉은 모래의 땅에 발을 들이세요.",
    "&8서쪽 &f레드로드&7 안쪽에 호수가 하나 있습니다. 물이 식지를 않는답니다.",
    "&8근처에는 아무도 가지 않는다고 합니다.",
])

# ══ ③ 수량 불일치 수리 — 목표는 16종인데 설명이 12종이었다 ══════════════════
setq("붉은사막02", 설명=[
    "&7붉은사막 물줄기의 어종은 본토와 전혀 다릅니다.",
    "&7붉은사막 도감을 &f16종&7 채워",
    "&7이 땅의 생태를 익히세요.",
    "&8의뢰: &7사피르",
])

# ══ ④ 카림 대사 — 과묵한 하오체. 자동생성 템플릿을 쓰지 않는다 ══════════════
if DLG is not None:
    ASK = [{"id": "c1", "text": "부탁을 들어볼게요", "action": "퀘스트목록", "next": "x"},
           {"id": "c2", "text": "조금 더 생각해볼게요", "action": "닫기", "next": "x"}]
    TAKE = [{"id": "c1", "text": "보상 받기", "action": "퀘스트목록", "next": "x"}]
    d = DLG.setdefault("카림", {})
    d["인사/사막11"] = {"lines": [
        "…제단에 올릴 게 필요하오.",
        "신선도 85 위로, A등급 둘. 상한 건 안 받소.",
        "제단 가운데가 패어 있는 건… 신경 쓰지 마시오. 원래 그랬소.",
        "…아니, 원래 그러진 않았지.",
    ], "choices": ASK}
    d["진행중/사막11"] = {"lines": ["…아직이오."], "choices": []}
    d["퀘스트완료/사막11"] = {"lines": [
        "됐소.",
        "…한 가지만. 서쪽 호수엔 가지 마시오.",
        "물이 식지를 않소. 이유는 나도 모르고, 알고 싶지도 않소.",
    ], "choices": TAKE}
    log.append(("카림.*/사막11", ["자동생성 템플릿"], ["과묵한 하오체로 다시 씀"]))

# ══ 저장 ═════════════════════════════════════════════════════════════════════
for path, obj in [(QP, Q)] + ([(DP, DLG)] if DLG is not None else []):
    shutil.copy(path, path + ".pre-ash")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=2)

for qid, b, a in log:
    print(f"\n[{qid}]")
    for l in (b or []):
        print("   -", l)
    for l in (a or []):
        print("   +", l)

# ── 검증 ─────────────────────────────────────────────────────────────────────
bad = []
# 보스는 아직 배선하지 않는다 — 실수로 들어갔는지 확인
for qid, e in QUESTS.items():
    for g in e["목표"]:
        if "식지않은재" in g or qid == "붉은사막04":
            bad.append(f"{qid}: 보스 배선이 들어갔다 — 보스 구현 전까지 금지")

# dogam 목표와 설명 수량이 맞는지 (③에서 고친 종류의 버그가 또 있는지)
def cl(s):
    return re.sub(r"&[0-9a-fk-or]", "", s)


for qid, e in QUESTS.items():
    for g in e["목표"]:
        p = g.split("|")
        if p[0] == "dogam":
            d = " ".join(cl(x) for x in e["설명"])
            nums = re.findall(r"(\d+)\s*종", d)
            if nums and p[2] not in nums:
                bad.append(f"{qid}: 도감 목표 {p[2]}종 / 설명 {nums}")

print("\n검증:", bad if bad else "이상 없음")
if bad:
    sys.exit("✗ 검증 실패")
print("✓ 완료. 반영: /데이터리로드")
print("  ★보스 `붉은사막04`는 아직 배선하지 않았다 — 보스 구현 후 별도 작업")
