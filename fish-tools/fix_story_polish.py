"""스토리 정합 보수 3종 (2026-08-14) — 텍스트 불일치 · 영주 라인 · 조각 획득 순간.

전수 검토에서 나온 지적을 순서대로 반영한다. `quests.json` + `npc.json` 동시 패치.

① 텍스트가 목표와 어긋난 것
   · `왕도02` 목표는 성문 위병 방문인데 설명이 "국왕 앞에 서세요"였다(설계가 바뀌며 설명만 남음).
   · `본섬10` 이름은 「심연어의 조각」인데 설명에 **조각이 한 글자도 없었다.**

② 영주 라인 — 발데마르가 죽어 있었다
   라이브는 근위병·사관만 상대하다 **마지막에 영주를 딱 한 번** 만나고 끝난다. 그래서
   냉담한 태도도, 보고를 미루는 갈등도, **동쪽 사막으로 가라는 명령**도 대사로 나오지 않는다.
   → 알현을 앞으로 당기고(영주02), 마지막을 「동쪽으로」(영주05)로 되돌린다.
   ★영주05는 `visit`이 아니라 **낚시 목표**로 바꾼다 — 목표를 채우고 **영주에게 반납하러 갈 때**
     명령이 떨어지는 구조라야 한다(`visit`는 만나는 즉시 완료라 대사를 얹을 자리가 없다).

③ 조각 획득 순간
   전설어를 낚는 칸(`본섬09`·`사막13`)과 「조각」 칸(`본섬10`·`사막14`)이 분리돼 있어
   정작 낚아 올린 순간에 아무 말이 없고, 두 번째 조각은 **촌장이 그냥 준다.**
   → 낚는 칸에서 "그 안에 있었다"를 말하고, 조각 칸은 **맡기고/확인하는** 자리로 고쳐 쓴다.

사용법 — quests.json·npc.json이 있는 디렉터리에서:
    python3 fix_story_polish.py
"""
import json, os, shutil, sys

QP, NP, DP = "quests.json", "npc.json", "dialogue.json"
Q = json.load(open(QP, encoding="utf-8"))
N = json.load(open(NP, encoding="utf-8"))
QUESTS, NPCS = Q["퀘스트"], N["npcs"]
DLG = json.load(open(DP, encoding="utf-8")) if os.path.exists(DP) else None
log = []

ASK = [{"id": "c1", "text": "부탁을 들어볼게요", "action": "퀘스트목록", "next": "x"},
       {"id": "c2", "text": "조금 더 생각해볼게요", "action": "닫기", "next": "x"}]
TAKE = [{"id": "c1", "text": "보상 받기", "action": "퀘스트목록", "next": "x"}]


def dnodes(npc, qid, greet, doing, done):
    """수여 NPC에 대화 3노드를 심는다. dialogue.json이 없으면 조용히 넘어간다."""
    if DLG is None:
        return
    d = DLG.setdefault(npc, {})
    d[f"인사/{qid}"] = {"lines": greet, "choices": ASK}
    d[f"진행중/{qid}"] = {"lines": doing, "choices": []}
    d[f"퀘스트완료/{qid}"] = {"lines": done, "choices": TAKE}
    log.append((f"{npc}.*/{qid}", {"대화": "없음"}, {"대화": "3노드 신설"}))


def q(qid):
    e = QUESTS.get(qid)
    if e is None:
        sys.exit(f"✗ {qid} 없음 — quests.json 경로를 확인하세요")
    return e


def setq(qid, **kw):
    e = q(qid)
    before = {k: e.get(k) for k in kw}
    e.update(kw)
    log.append((qid, before, {k: e.get(k) for k in kw}))


