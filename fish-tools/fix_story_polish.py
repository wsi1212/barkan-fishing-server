# NPC 재배정 — 근위병 01·03 / 영주 02·05 / 사관 04
ASSIGN = {"근위병": ["영주01", "영주03"], "영주": ["영주02", "영주05"], "사관": ["영주04"]}
ALL = {v for vs in ASSIGN.values() for v in vs}
for key, qids in ASSIGN.items():
    if key not in NPCS:
        sys.exit(f"✗ npc.json에 {key} 없음")
    cur = NPCS[key].setdefault("quests", [])
    cur[:] = [x for x in cur if x not in ALL]          # 영주 라인 전부 제거 후
    for i, qid in enumerate(qids):                     # 메인을 앞에 다시 꽂는다
        cur.insert(i, qid)

# ★대화 노드도 수여자를 따라가야 한다 — 옮기지 않으면 새 수여자는 기본 대사로
#   떨어지고, 옛 수여자에겐 아무도 도달 못 하는 죽은 노드가 남는다.
