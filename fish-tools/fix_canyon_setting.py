#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""「검은 섬」 폐기 — 물 밖으로 솟은 것은 아무것도 없다 (2026-08-14 설정 정정).

■ 무엇이 틀렸나
  5챕터 `배상단08`에서 견시 니코가 **"수평선 너머 검은 섬을 봤어"** 라고 말하고,
  7챕터 3막이 그 섬에 올라가 **「교단의 전초 = 제단」** 을 치는 구조였다. 전부 폐기한다.

  · 제단은 **물 밖에 없다.** 심해 월드 안 「무명의 성소」에 있고, 그게 교단의 **유일한** 본부다.
  · 협곡 근처 바다에 있는 것은 **표식 몇 개**뿐이다. 건물이 아니다.
  · 니코가 「섬」이라 부른 것은 안개 너머로 보이는 **검게 꺼진 자리** —
    실은 **협곡을 위에서 본 모습**이다. 솟은 게 아니라 꺼져 있었다.

  이 편이 낫다. 「섬을 봤다」는 목격이 5챕터에서 7챕터까지 그대로 이어지는 대신,
  **본 것을 잘못 불렀다**는 정정이 3막의 첫 비트가 된다. 그리고 5챕터의 목격과
  7챕터의 협곡이 **같은 것**이 되어 복선이 하나로 묶인다.

■ 용어 통일 (다른 말로 부르지 말 것)
  안개 해역 / 꺼진 자리 / 심해 협곡 / 교단의 표식 / 무명의 성소
  ⇒ 「검은 섬」·「안개섬」·「전초의 제단」은 폐기.

■ 이 스크립트가 하는 일
  ① `배상단08` — 니코의 목격을 「섬」에서 「꺼진 자리」로 고쳐 쓴다 (5챕터, 라이브)
  ② `왕도06` — 보고 내용을 같은 어휘로 (6챕터, 라이브)
  ③ `교단의표식` 어종 신설 — `심해15`가 이걸 3개 건진다 (7챕터, 생성기 소관이지만
     어종 정의는 fish.json이라 여기서 넣는다)

★7챕터 퀘스트 본문은 `build_ch7_quests.py`가 권위다 — 3막 재구성(마탑을 4막에서
  3막으로 올린 것 포함)은 그쪽에 이미 반영돼 있다.

사용법 — quests.json·fish.json이 있는 디렉터리에서 (`drop_blackscale_line.py` 다음):
    python3 fix_canyon_setting.py
"""
import json, re, shutil, sys

QP, FP = "quests.json", "fish.json"
Q = json.load(open(QP, encoding="utf-8"))
F = json.load(open(FP, encoding="utf-8"))
QUESTS, FISH, REGIONS = Q["퀘스트"], F["fish"], F["regions"]
log = []


def setdesc(qid, desc):
    e = QUESTS.get(qid)
    if e is None:
        sys.exit(f"✗ {qid} 없음")
    log.append((qid, e["설명"], desc))
    e["설명"] = desc


# ══ ① 5챕터 — 목격의 정정 ════════════════════════════════════════════════════
setdesc("배상단08", [
    "&7망대의 견시 &f니코&7: \"안개 낀 날, 수평선 너머에 검은 게 있었어.\"",
    "&7\"섬인 줄 알았지. 근데 아무리 봐도 &f솟은 게 아니야&7.\"",
    "&7\"...물이 꺼져 있었어. 세 번 봤다고. 아무도 안 믿지만.\"",
    "&7그 바다에서 올린 &fS등급 3마리&7가 증거가 됩니다.",
])

# ══ ② 6챕터 — 같은 어휘로 보고 ═══════════════════════════════════════════════
setdesc("왕도06", [
    "&7안개 너머에서 본 것을 왕에게 고하러 돌아갑니다.",
    "&8해도에 없는 안개, 그 너머에 물이 꺼진 자리가 있었다는 것.",
    "&8도란과 마르코는 끌려갔고 상단은 해체됐습니다.",
    "&8은빛 갈매기호는 왕실에 압류됐습니다 — 그런데도 끝난 것 같지 않습니다.",
    "&7왕도로 향하세요.",
])

# ══ ③ 교단의표식 — 심해15가 건지는 것 ════════════════════════════════════════
NAME, REGION, GATE = "교단의표식", "대양", "심해15"
if NAME in FISH:
    sys.exit(f"✗ `{NAME}`이 이미 있습니다 — 중단")
# 기존 물건 증거(교단의인장·교단의해도 등)와 완전히 같은 스키마
FISH[NAME] = {"minSize": 1, "maxSize": 1, "grade": "E",
              "time": "전체", "weather": "전체", "quest": GATE}
sub = REGIONS.get(REGION)
if sub is None or "기본" not in sub:
    sys.exit(f"✗ regions.{REGION}.기본 이 없습니다")
if NAME not in sub["기본"]:
    sub["기본"].append(NAME)
log.append(("fish.json", [], [f"`{NAME}` 신설 — regions.{REGION}.기본 · quest={GATE}"]))

# ══ ④ 라이브에 옛 7챕터가 깔려 있으면 그 두 칸도 맞춰 둔다 ═══════════════════
#    (권위는 build_ch7_quests.py지만, 생성기를 돌리기 전까지 라이브가 옛 설정을
#     그대로 말하고 있으면 곤란하다. drop_blackscale_line.py의 심해09 처리와 같은 방침.)
if "심해14" in QUESTS:
    QUESTS["심해14"]["이름"] = "&9섬이 아니었다"
    setdesc("심해14", [
        "&7안개가 옅어진 자리에 &f검게 꺼진 바다&7가 있습니다.",
        "&7니코: \"저거야. 내가 섬이라고 했던 거.\"",
        "&7\"...근데 섬이 아니야. 솟은 게 아니라 &f꺼져&7 있어.\"",
        "&f테클라&7에게 보고하세요.",
    ])
if "심해15" in QUESTS:
    QUESTS["심해15"]["이름"] = "&9바다에 남은 표식"
    QUESTS["심해15"]["목표"] = ["fish|교단의표식|아무|3|0"]
    setdesc("심해15", [
        "&7테클라: \"건물은 없어요. 저들은 물 위에 아무것도 안 지어요.\"",
        "&7\"대신 자리를 표시해 뒀죠 — 자기들이 길을 잃지 않으려고.\"",
        "&7알비스가 짚어 준 자리에서 &f교단의 표식&7 3개를 건져 올리세요.",
    ])

# ══ 저장 ═════════════════════════════════════════════════════════════════════
for path, obj in ((QP, Q), (FP, F)):
    shutil.copy(path, path + ".pre-canyon")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=2)

for qid, b, a in log:
    print(f"\n[{qid}]")
    for l in b:
        print("   -", l)
    for l in a:
        print("   +", l)

# ── 검증 ─────────────────────────────────────────────────────────────────────
BAD = re.compile(r"검은 ?섬|안개섬|전초")
hits = []
for qid, e in QUESTS.items():
    blob = " ".join([e["이름"]] + list(e["설명"]))
    if BAD.search(blob):
        hits.append(qid)
print("\n남은 「검은 섬」 계열 표현:", hits if hits else "없음")
if hits:
    sys.exit("✗ 검증 실패 — 7챕터라면 build_ch7_quests.py를 확인할 것")
print("✓ 완료. 반영: /데이터리로드")
