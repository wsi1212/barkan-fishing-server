"""금서를 소품에서 **장치**로 (2026-08-14 확정) + 무대를 왕궁 하나로.

■ 무엇이 문제였나
  ① 「위작」이 정체불명이었다 — `왕도08` 설명은 *"누군가 원본을 위조하고 삭제한 흔적"* 이
     전부였다. **무엇을, 어떻게, 왜** 위조했는지가 없다. 게다가 필사실은 베껴 쓰는 곳이지
     원본을 두는 곳이 아니고(원본은 금서고에 있다), 검열이면 없애면 되지 굳이 위조할
     이유도 없었다.
  ② **금서가 소품이었다.** 이름을 꺼내려고 존재하고, 꺼낸 뒤로는 어디에도 안 나온다.
     복선으로 돌아오지도 않는다.

■ 새 설정 — 금서 = 봉인 그 자체
  봉인은 **이름을 아는 자가 세상에 없게 만드는 것**이다(4챕터 국왕 대사의 논리 그대로).
  다만 왕실도 완전히 잊으면 안 되니 **딱 한 권에만 남겼다.** 그게 금서다.
  ⇒ **낱장이 뜯겼다 = 부를 수 있는 유일한 사본이 저들 손에 넘어갔다.**
  6챕터의 공포가 「누가 훔쳤나」에서 **「이미 늦었다」** 로 바뀐다.

  「위조」는 통째로 폐기한다. 남는 건 **뜯겨 나갔다** 하나뿐이다.

■ 복선이 세 번 돌아온다
  6챕터        낱장 셋이 없다 → 저들은 이미 부를 수 있다 → 왕에게 **경보**
  7챕터 심해30  성소 기록고 벽 끝에 **훔쳐 간 낱장 셋**이 걸려 있다 → 되찾는다
  에필로그      낱장이 어부 손에 있다 → **이제 부를 수 있는 사람이 어부다**
  ★7챕터·에필로그 몫은 `build_ch7_quests.py`가 권위다(이 스크립트는 6챕터까지).

■ 「물이 기억한다」로 이름을 복원한다
  종이는 지울 수 있어도 **물에 남은 잔향은 못 지운다.** 그게 검열의 한계이자 이 게임의
  제1설정(낚시 = 땅의 기억을 읽는 행위)이다. 7챕터 알비스의 *"기록이 없으면 물에게 묻게"*
  와 같은 논리다.
  ⇒ `금서의조각` → **`잊혀진이름`** 개명. 옛 이름은 두 가지가 걸렸다 —
     뜯긴 종이를 건지는 것처럼 읽히고(실제로는 기억을 읽는 것),
     2챕터부터 모아 온 **「심연어의 조각」과 단어가 겹쳐** 네 번째 조각으로 오인된다.

■ 무대 — 왕립 대도서관 건물은 삭제됐다
  **왕궁 안의 도서관**으로 일원화한다. 6챕터 동선이 전부 왕궁 안에서 끝난다.

사용법 — quests.json·fish.json·dialogue.json이 있는 디렉터리에서:
    python3 fix_forbidden_book.py
"""
import json, os, re, shutil, sys

QP, FP, DP = "quests.json", "fish.json", "dialogue.json"
Q = json.load(open(QP, encoding="utf-8"))
