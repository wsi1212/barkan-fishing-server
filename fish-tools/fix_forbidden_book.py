QUESTS, FISH, REGIONS = Q["퀘스트"], F["fish"], F["regions"]
DLG = json.load(open(DP, encoding="utf-8")) if os.path.exists(DP) else None
log = []

OLD_FISH, NEW_FISH = "금서의조각", "잊혀진이름"


def setq(qid, **kw):
    e = QUESTS.get(qid)
    if e is None:
        sys.exit(f"✗ {qid} 없음")
    before = {k: e.get(k) for k in kw}
    e.update(kw)
    log.append((qid, before, {k: e.get(k) for k in kw}))


# ══ 어종 개명 ════════════════════════════════════════════════════════════════
if OLD_FISH in FISH:
    FISH[NEW_FISH] = FISH.pop(OLD_FISH)
    for rg, subs in REGIONS.items():
        for sub, lst in subs.items():
            if isinstance(lst, list) and OLD_FISH in lst:
                lst[lst.index(OLD_FISH)] = NEW_FISH
    log.append(("fish.json", {"어종": OLD_FISH}, {"어종": NEW_FISH}))
elif NEW_FISH not in FISH:
    sys.exit(f"✗ `{OLD_FISH}`도 `{NEW_FISH}`도 없습니다")

