# 목표 문구가 끼는 가변 템플릿 3종 — 앞뒤만 갈아 끼운다
VARIABLE = [
    (re.compile(r"^이번에 맡길 일은 (.+?)이라네\.$"),   r"이번에 맡길 일은 \1이에요."),
    (re.compile(r"^해야 할 일은 (.+?)이라네\.$"),       r"해야 할 일은 \1이에요."),
    (re.compile(r"^먼저 (.+?)부터 해보면 되네\.$"),     r"먼저 \1부터 해 보시면 돼요."),
]

QNODE = re.compile(r"^(인사/|진행중/|퀘스트완료/|첫만남$|후일담$)")
OLD = re.compile(r"(이라네|자네|하자꾸나|겠나\?|주게\.|보게\.|하게\.|구나\.)")

changed, untouched = [], []
for npc in sorted(TARGETS):
    nodes = D.get(npc)
    if not isinstance(nodes, dict):
        sys.exit(f"✗ dialogue.json에 {npc} 없음")
    for key, n in nodes.items():
        if not QNODE.match(key):
            continue                       # 손으로 쓴 인격 노드는 건드리지 않는다
        lines = (n or {}).get("lines") or []
        for i, l in enumerate(lines):
            new = FIXED.get(l)
            if new is None:
                for pat, rep in VARIABLE:
                    if pat.match(l):
                        new = pat.sub(rep, l)
                        break
            if new and new != l:
                lines[i] = new
                changed.append((npc, key, l, new))
            elif OLD.search(l):
                untouched.append((npc, key, l))

shutil.copy(DP, DP + ".pre-tone")
with open(DP, "w", encoding="utf-8") as f:
    json.dump(D, f, ensure_ascii=False, indent=2)

by_npc = {}
for npc, key, b, a in changed:
    by_npc.setdefault(npc, 0)
    by_npc[npc] += 1
print(f"교체 {len(changed)}줄 · {len(by_npc)}명")
for npc, n in sorted(by_npc.items(), key=lambda x: -x[1]):
    print(f"  {npc:12} {n}줄")

print("\n샘플 —")
for npc, key, b, a in changed[:8]:
    print(f"  [{npc}.{key}]\n     - {b}\n     + {a}")

if untouched:
    print(f"\n★남은 노인 말투 {len(untouched)}줄 — 템플릿 밖(손으로 쓴 대사)이라 자동 교체하지 않았다:")
