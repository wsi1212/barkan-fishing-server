OLD = re.compile(r"(이라네|자네|하자꾸나|겠나\?|주게\.|보게\.|하게\.|구나\.|되네\.)")

changed, left = [], []
for npc, voice in sorted(VOICE.items()):
    nodes = D.get(npc)
    if not isinstance(nodes, dict):
        sys.exit(f"✗ dialogue.json에 {npc} 없음")
    for key, n in nodes.items():
        if not QNODE.match(key):
            continue                      # 손으로 쓴 인격 노드는 건드리지 않는다
        lines = (n or {}).get("lines") or []
        for i, l in enumerate(lines):
            new = None
            row = T.get(l)
            if row:
                new = row[IDX[voice]]
            else:
                for pat, reps in VAR:
                    if pat.match(l):
                        new = pat.sub(reps[voice], l)
                        break
            if new and new != l:
                lines[i] = new
                changed.append((npc, voice, key, l, new))
            elif OLD.search(lines[i]):
                left.append((npc, voice, key, lines[i]))

shutil.copy(DP, DP + ".pre-tone")
