# ══ 저장 ═════════════════════════════════════════════════════════════════════
shutil.copy(DP, DP + ".pre-blackscale")
with open(DP, "w", encoding="utf-8") as f:
    json.dump(D, f, ensure_ascii=False, indent=2)

for where, b, a in log:
    print(f"\n[{where}]")
    for l in b:
        print("   -", l)
    for l in a:
        print("   +", l)

# ── 검증 ─────────────────────────────────────────────────────────────────────
KEY = re.compile(r"검은비늘|오염|검게 죽")


def walk(o, path=""):
    if isinstance(o, dict):
        for k, v in o.items():
            yield from walk(v, f"{path}.{k}")
    elif isinstance(o, list):
        for i, v in enumerate(o):
            yield from walk(v, f"{path}[{i}]")
    elif isinstance(o, str):
        yield path, o


bad = [(p, s) for p, s in walk(D) if KEY.search(s)]
print("\n남은 오염 표현:", bad if bad else "없음")
if bad:
    sys.exit("✗ 검증 실패")
print("✓ 완료. 반영: /데이터리로드")
