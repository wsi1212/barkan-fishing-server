# ── 검증 — 남은 수량/등급 불일치가 없어야 한다 ───────────────────────────────
cur, seen, chain = "튜토_길드", set(), []
while cur and cur in QUESTS and cur not in seen:
    seen.add(cur); chain.append(cur); cur = QUESTS[cur].get("다음퀘스트")


def cl(s):
    return re.sub(r"&[0-9a-fk-or]", "", s)


bad = []
for k in chain:
    if k.startswith("심해") or k.startswith("알비스"):
        continue                      # build_ch7_quests.py 소관
    e = QUESTS[k]
    d = " ".join(cl(x) for x in e["설명"])
    for g in e["목표"]:
        p = g.split("|")
        if p[0] in ("fish", "fish_fresh", "harpoon"):
            gr, n = p[2], p[3]
            nums = re.findall(r"(\d+)\s*마리", d)
            if nums and n not in nums:
                bad.append(f"{k} 수량 {n}≠{nums}")
            if gr != "아무" and gr not in d:
                bad.append(f"{k} 등급 {gr} 미언급")

print("\n남은 불일치:", bad if bad else "없음")
if bad:
    sys.exit("✗ 검증 실패")
