#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""폭포 뒤 동굴을 초반 동선에서 떼어낸다 + 2챕터 폐사당·오염 위치 정정 (2026-08-14).

★배경 — 폭포 뒤 동굴은 **완전히 별개의 사이드 라인**이다(Lv30~80 낚시 계단, 6층 이무기·꽃).
  메인 스토리도, 초반 사이드도 그 안으로 들어가지 않는다. 그런데 라이브 실측 결과
  **Lv3~5짜리 퀘스트 3개가 `폭포_뒤_동굴_1층`을 목표로 걸고 있었다.**

  그대로 두면 사이드 축 과제(1층 `requiredLevel` 0 → 30)를 적용하는 순간 셋 다 하드블록이 된다.
  특히 `본섬03`은 메인이라 2챕터 전체가 Lv3에서 멈춘다.

★같이 고치는 것 — 2챕터 무대 정정(유저 확인):
  · 폐사당은 늪지대가 아니라 **대수림**에 있다.
  · 폐사당은 오염된 곳이 아니다. 검게 죽은 비늘이 나오는 물은 **강**이다
    (fish.json 실측: `검은비늘붕어` → `regions.강.기본`, grade D, `quest:본섬07`).

사용법 — quests.json이 있는 디렉터리에서 실행:
    python3 fix_waterfall_cave_refs.py

★`심해20`은 건드리지 않는다. 그쪽은 `build_ch7_quests.py`가 권위이고,
  `area|심해협곡`으로 바뀌려면 협곡 지역이 먼저 등록돼야 한다.
"""
import json, shutil, sys

QP = "quests.json"
Q = json.load(open(QP, encoding="utf-8"))
QUESTS = Q["퀘스트"]

CAVE1 = "area|폭포_뒤_동굴_1층"


def q(qid):
    e = QUESTS.get(qid)
    if e is None:
        sys.exit(f"✗ {qid} 없음 — quests.json 경로를 확인하세요")
    return e


def drop_goal(e, goal):
    before = list(e["목표"])
    e["목표"] = [g for g in e["목표"] if g != goal]
    return before, list(e["목표"])


changes = []

# ── ① 본섬03 (메인 Lv3) — 폭포 뒤 동굴 → 협곡 ────────────────────────────────
#   2-3은 폭포 뒤 동굴이 아니라 실제 초반 동선인 협곡을 무대로 쓴다.
#   어부 노인은 숲에 사는 인물이 아니므로, 장소와 퀘스트 이름을 협곡 기준으로 맞춘다.
e = q("본섬03")
b = list(e["목표"])
e["목표"] = ["area|협곡" if g == CAVE1 else g for g in e["목표"]]
e["이름"] = "&e[2-3] 협곡의 물길"
e["설명"] = [
    "&7마을 북쪽으로 이어지는 &f협곡&7의 물길을 찾아가세요.",
    "&7깎아지른 절벽 아래에서 &fD~C등급 물고기 4마리&7를 낚아 오세요.",
    "&8의뢰: &7어부 노인",
]
changes.append(("본섬03", b, list(e["목표"]), "폭포 뒤 동굴 → 협곡 + 퀘스트명 정정"))

# ── ② 본섬04 (메인 Lv4) — 이름이 '폭포 뒤'로 유도한다 ─────────────────────────
#   설명은 이미 "폭포 아래 웅덩이"로 맞다. 이름만 어긋나 있었다.
#   덤으로 설명("10마리")과 목표(8마리)가 불일치라 함께 맞춘다.
e = q("본섬04")
old_name = e["이름"]
e["이름"] = "&e폭포 아래 웅덩이"
e["타입"] = "물고기"          # 목표가 낚시뿐인데 「지역」으로 적혀 있었다(문서용 필드라 동작엔 무관)
e["설명"] = [
    "&7폭포 아래 웅덩이는 물고기가 모여듭니다.",
    "&7&f25cm 이상&7으로 8마리 잡아보세요.",
    "&8의뢰: &7어부 노인",
]
changes.append(("본섬04", [old_name], [e["이름"]], "이름 정정 + 설명 수량 10→8 일치"))

# ── ③ 본사이드_노인02 (사이드 Lv5) — 「폭포의 비밀」 ──────────────────────────
#   이 퀘스트는 의도적으로 `폭포` 표식 지역을 방문·낚시 조건으로 사용한다.
e = q("본사이드_노인02")
b = list(e["목표"])
e["목표"] = ["area|폭포" if g in {"area|폭포", CAVE1} else
             ("fish|아무|아무|5|0|폭포"
              if g.startswith("fish|아무|아무|5|0") else g)
             for g in e["목표"]]
changes.append(("본사이드_노인02", b, list(e["목표"]), "방문·낚시 조건을 폭포 지역으로 통일"))

# ── ④ 본사이드_세르간03 (사이드 Lv5) — 「동굴의 비밀」 ────────────────────────
#   세르간 라인은 늪지대·폐사당과 엮인다. 어종도 46종으로 넉넉하다.
e = q("본사이드_세르간03")
b = list(e["목표"])
e["목표"] = ["area|늪지대" if g == CAVE1 else g for g in e["목표"]]
e["이름"] = "&a늪지대의 비밀"
changes.append(("본사이드_세르간03", b, list(e["목표"]), "폭포 뒤 동굴 → 늪지대 + 이름 정정"))

# ── ⑤ 본섬06 (메인 Lv6) — 폐사당은 대수림에 있다 ─────────────────────────────
#   ★`대수림`은 fish.json에 자체 어종이 0종이다 → `dogam|대수림|6`은 채울 수 없다.
#     그래서 도감 목표는 뺀다. 대수림에 어종(또는 parentIsland)이 붙으면 되살릴 것.
e = q("본섬06")
b = list(e["목표"])
e["목표"] = ["area|대수림"]
e["설명"] = [
    "&7강 너머 &f대수림&7 깊은 곳,",
    "&7버려진 폐사당 터를 찾아가 보세요.",
    "&8의뢰: &7세르간",
]
changes.append(("본섬06", b, list(e["목표"]), "폐사당 무대 늪지대 → 대수림 (도감 목표는 어종 0종이라 제외)"))

# ── ⑥ 본섬07 (메인 Lv7) — 오염의 자리는 강이다 ───────────────────────────────
#   폐사당은 교단이 다녀간 흔적일 뿐이고, 물이 썩은 곳은 마을 앞 강이다(fish.json 실측).
e = q("본섬07")
old = list(e["설명"])
e["설명"] = [
    "&7폐사당의 물은 멀쩡한데,",
    "&7&f마을 앞 강&7에서 비늘이 검게 죽은 놈이 올라옵니다.",
    "&7&f검은비늘붕어&7를 1마리 잡으세요.",
    "&8의뢰: &7세르간",
]
changes.append(("본섬07", old, list(e["설명"]), "오염 위치 정정 — 폐사당 근처 → 마을 앞 강"))

# ── 저장 ─────────────────────────────────────────────────────────────────────
shutil.copy(QP, QP + ".pre-cavefix")
with open(QP, "w", encoding="utf-8") as f:
    json.dump(Q, f, ensure_ascii=False, indent=2)

for qid, b, a, why in changes:
    print(f"\n[{qid}] {why}")
    print(f"   before: {b}")
    print(f"   after : {a}")

# ── 검증 ─────────────────────────────────────────────────────────────────────
left = {k: v.get("목표") for k, v in QUESTS.items()
        if any("폭포_뒤_동굴" in g for g in (v.get("목표") or []))}
print("\n남은 폭포_뒤_동굴 참조:", left if left else "없음")
if set(left) - {"심해20"}:
    sys.exit("✗ 초반 퀘스트에 아직 폭포 뒤 동굴 참조가 남아 있습니다")
if "심해20" in left:
    print("  └ 심해20은 build_ch7_quests.py가 권위 — 협곡 지역 등록 후 그쪽에서 area|심해협곡으로 교체")
print("\n✓ 완료. 반영: /데이터리로드")
