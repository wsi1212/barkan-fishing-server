    # ★NPC는 옮기지 않는다 — 그녀는 상단마을에 그대로 있고 **플레이어만** 오아시스에 다녀온다.
    #   Citizens NPC는 전역(한 명)인데 진행도는 유저별이다. 그녀를 사막으로 옮기면
    #   ①아직 04·05를 안 한 유저가 상단마을에서 그녀를 못 만나 체인이 끊기고
    #   ②목표 달성 뒤 **반납할 NPC**까지 사라진다.
    #   그래서 이사는 «지원한다 → 다음 배로 떠난다»는 예고로만 남긴다.
    ("상사이드_레일라06", 43, "복합", "&a물을 지키는 일", 34000, 2200,
     ["&7레일라: \"사막에서 &f오아시스 감시원&7을 뽑는다고 하네요.\"",
      "&7\"물류를 알던 사람이 물을 지키면… 쓸모가 있을까요.\"",
      "&7지원서에 붙일 표본이 필요합니다. 오아시스를 직접 보고 와 주세요.",
      "&f오아시스 도착&7 + &f A등급 이상 5마리&7 — 돌아와 그녀에게 전하세요.",
      "&8의뢰: &7레일라"],
     ["area|오아시스", "fish|아무|A|5|0"]),
