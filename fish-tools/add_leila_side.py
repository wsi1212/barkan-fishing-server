#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""레일라 후일담 사이드 3단 신설 — 「내부고발자의 대가」 (2026-08-14).

★공백 — 레일라는 3챕터에서 소속과 양심 사이에 서서 상단의 지하수 절취를 제보했다(`사막10`).
  그 제보가 4·5챕터를 굴려 결국 상단을 무너뜨리는데, **정작 그녀가 어떻게 됐는지는 아무도 말하지 않는다.**
  기존 사이드 3개(`상사이드_레일라01~03`)는 전부 상단이 살아 있던 시절의 잠입물이라
  붕괴 이후를 다루지 않는다.

★설계 — 3단 서사 체인. 상단이 무너진 뒤에만 열린다(`선행 = 배상단08`).
  ① 옳았지만 대가를 치른다 → ② 남은 것이 기억뿐임을 증명한다 → ③ 새 자리를 얻는다.
  종착은 **오아시스 감시원** — 물류를 알던 사람이 물을 지키는 자리다.
  3챕터의 물 문제, 7챕터 사피르의 오아시스 회복과 같은 실에 묶인다.

★기존 사이드와 다른 점 — `상사이드_레일라01~03`은 반복형(평행, 다음퀘스트 없음)이지만
  이 셋은 **순차 체인**이다. 사이드→사이드 체인은 이미 19건 선례가 있다(해바라기·노파·동굴 등).

★★**NPC는 절대 옮기지 않는다 — 서사가 인물을 이사시켜도 마찬가지다.**
  Citizens NPC는 **전역으로 한 명**인데 퀘스트 진행도는 **유저별**이다. 그래서 인물이 이동하면
  아직 앞 단계를 안 한 유저는 그를 못 만나고(수락 불가), 목표를 끝낸 유저는 반납할 상대를 잃는다.
  이 라인에서 움직이는 것은 **플레이어**다(`area|오아시스`). 레일라는 상단마을에 그대로 있다.
  ※전역 이동 자체가 금지는 아니다 — 진행도와 무관한 일회성 배치 변경(예: 어부 노인을 숲으로)은 괜찮다.
    문제는 **유저별 진행에 따라 위치가 달라져야 하는** 경우다.

사용법 — quests.json·npc.json이 있는 디렉터리에서 실행:
    python3 add_leila_side.py
"""
import json, os, shutil, sys

QP, NP, DP = "quests.json", "npc.json", "dialogue.json"
Q = json.load(open(QP, encoding="utf-8"))
N = json.load(open(NP, encoding="utf-8"))
QUESTS, NPCS = Q["퀘스트"], N["npcs"]
DLG = json.load(open(DP, encoding="utf-8")) if os.path.exists(DP) else None

if "레일라" not in NPCS:
    sys.exit("✗ npc.json에 레일라 없음")
if "배상단08" not in QUESTS:
    sys.exit("✗ 배상단08 없음 — 선행으로 걸 수 없다")

# 레벨·보상 스케일: 배상단08(메인 Lv40, 40,000/2,625) 직후 구간.
