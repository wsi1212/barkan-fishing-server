def build_stats(grade, line):
    """등급 기반 + 라인 가산. 혼합형(튜플)은 두 라인을 0.6 배씩 섞는다."""
    out = dict(BASE[grade])
    lines = line if isinstance(line, tuple) else (line,)
    w = 1.0 if len(lines) == 1 else 0.6
    for ln in lines:
        for k, v in LINES[ln].get(grade, {}).items():
            add = v if w == 1.0 else (max(1, int(round(v * w))) if v > 0
                                      else min(-1, int(round(v * w))))
            out[k] = out.get(k, 0) + add
    # ★음수 가산(관통 D 의 수중호흡 −5)은 1 미만으로 못 내려간다 — 0 이면 스탯이 사라진다.
    return {k: max(1, v) for k, v in out.items() if v}


def ordered(stats):
    return {k: stats[k] for k in STAT_ORDER if k in stats}


