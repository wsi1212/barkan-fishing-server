    a = ap.parse_args()
    M = HV.Model()

    plan = {}
    for name, (grade, line) in ASSIGN.items():
        plan[name] = dict(grade=grade, line=line if isinstance(line, str) else "+".join(line),
                          stats=ordered(build_stats(grade, line)))
    if a.plan:
        print(json.dumps({"assign": plan, "new": NEW}, ensure_ascii=False, indent=1))
        return

    print("작살 라인 설계 — 등급 기반 + 라인 가산")
    print(f"  ★제거: {', '.join(DEAD)} (모델상 전 레벨 0원/h — 코드 쿨타임 0.25s < 실측 조준 1.295s)")
    print(f"  ★신규 채집형 3종: {', '.join(NEW)}")

    def perf(name, grade, lvl, stats):
        d = M.dist_for(lvl)
        b = M.income(M.effective("나무 작살"), d)
        s = dict(stats)
        s["수중호흡"] = max(s.get("수중호흡", 0), HV.BREATH_FLOOR.get(grade, 5))
        s["공격력"] = max(1, s.get("공격력", 0))
        return M.income(s, d) - b

    for grade in ["D", "C", "B", "A", "G"]:
        rows = [(n, v) for n, v in plan.items() if v["grade"] == grade]
        if not rows:
            continue
        print(f"\n{'='*112}\n[{grade}]\n{'='*112}")
        print(f"{'이름':<14}{'라인':<10}{'순성능/h':>11}{'해금':<8}  스탯")
        for n, v in sorted(rows, key=lambda x: x[1]["line"]):
            lvl = M.spears[n]["lvl"] if n in M.spears else NEW[n][1]
            p = perf(n, grade, lvl, v["stats"])
            s2 = dict(v["stats"])
            s2["수중호흡"] = max(s2.get("수중호흡", 0), HV.BREATH_FLOOR.get(grade, 5))
            unlocked = [g for g in ("C", "B", "A", "S") if M.p_catch(g, s2)[0] >= M.P_THRESHOLD]
            print(f"{n:<14}{v['line']:<10}{p:>11,.0f}  ~{unlocked[-1] if unlocked else '-':<6}  "
                  + ", ".join(f"{k}{x}" for k, x in v["stats"].items()))


